-- Modelo de seguridad:
--  * Los clientes NO tienen cuenta ni acceso directo a la base: el pedido lo crea el servidor
--    (/api/checkout) con la clave service_role, despues de validar precios y datos.
--  * Solo los usuarios de la tabla `admins` pueden leer y actualizar pedidos (panel /admin).

create table if not exists public.orders (
  id uuid primary key,
  items jsonb not null,
  total_cop integer not null check (total_cop > 0),
  status text not null default 'pendiente',
  created_at timestamptz not null default now()
);

-- Datos del cliente y de la entrega a domicilio
alter table public.orders add column if not exists numero bigint generated by default as identity;
alter table public.orders add column if not exists nombre text;
alter table public.orders add column if not exists telefono text;
alter table public.orders add column if not exists email text;
alter table public.orders add column if not exists departamento text;
alter table public.orders add column if not exists ciudad text;
alter table public.orders add column if not exists direccion text;
alter table public.orders add column if not exists indicaciones text;
alter table public.orders add column if not exists notas text;

create index if not exists orders_created_idx on public.orders (created_at desc);
create index if not exists orders_status_idx on public.orders (status);

-- Administradores (usuarios de Supabase Auth autorizados a ver pedidos)
create table if not exists public.admins (
  user_id uuid primary key references auth.users (id) on delete cascade
);

alter table public.orders enable row level security;
alter table public.admins enable row level security;

create or replace function public.is_admin() returns boolean
  language sql security definer set search_path = public stable
  as $$ select exists (select 1 from public.admins where user_id = auth.uid()) $$;

-- Se retira el acceso anonimo anterior: ya nadie crea pedidos desde el navegador.
drop policy if exists "crear pedidos" on public.orders;
revoke all on public.orders from anon;
revoke all on public.admins from anon;

drop policy if exists "admin lee pedidos" on public.orders;
create policy "admin lee pedidos" on public.orders for select to authenticated using (public.is_admin());

drop policy if exists "admin actualiza pedidos" on public.orders;
create policy "admin actualiza pedidos" on public.orders for update to authenticated
  using (public.is_admin()) with check (public.is_admin());

drop policy if exists "admin se ve a si mismo" on public.admins;
create policy "admin se ve a si mismo" on public.admins for select to authenticated using (user_id = auth.uid());

revoke all on public.orders from authenticated;
grant select on public.orders to authenticated;
grant update (status) on public.orders to authenticated;
grant select on public.admins to authenticated;
